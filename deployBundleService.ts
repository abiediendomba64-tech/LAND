export async function createDeployZip(
  ampConfig: AmpConfig,
  portalConfig: PortalConfig,
  registerConfig: RegisterConfig,
  safelinkConfig: SafeLinkConfig,
  cyberShieldConfig: CyberShieldConfig,
  cdnScripts: CdnScriptConfig,
  options: DeployPackageOptions = {
    primaryLanding: 'amp',
    includeHtaccess: true,
    includeCloudflareConfig: true,
    includeGithubPagesConfig: true,
    includeSitemap: true,
    includeCyberShield: true,
  }
): Promise<Blob> {
  const zip = new JSZip();
  const brand = portalConfig.siteName || ampConfig.brandName || 'OFFICIAL VIP';

  // 1. Generate Individual HTML Strings
  const ampHtml = generateAmpHtml({ ...ampConfig, cyberShield: cyberShieldConfig });
  const portalHtml = generatePortalHtml(
    { ...portalConfig, cyberShield: cyberShieldConfig },
    cdnScripts.scripts
  );
  const registerHtml = generateVipRegisterHtml(
    { ...registerConfig, cyberShield: cyberShieldConfig },
    cdnScripts.scripts
  );
  const safelinkHtml = generateSafeLinkHtml(
    { ...safelinkConfig, cyberShield: cyberShieldConfig },
    cdnScripts.scripts
  );
  const cyberShieldJs = generateCyberShieldScript(cyberShieldConfig, brand);

  // 2. Primary index.html
  const primaryHtml = options.primaryLanding === 'amp' ? ampHtml : portalHtml;
  zip.file('index.html', primaryHtml);

  // 3. Named page files
  zip.file('amp.html', ampHtml);
  zip.file('portal.html', portalHtml);
  zip.file('register.html', registerHtml);
  zip.file('safelink.html', safelinkHtml);

  // 4. Standalone CyberShield module
  if (options.includeCyberShield) {
    zip.file('cyber-shield.js', cyberShieldJs);
  }

  // 5. SEO & Crawlers
  const robotsTxt = generateRobotsTxt(ampConfig.canonicalUrl || 'https://vip-official.pages.dev/');
  zip.file('robots.txt', robotsTxt);

  if (options.includeSitemap) {
    const sitemapXml = generateSitemapXml(
      ampConfig.canonicalUrl || 'https://vip-official.pages.dev/',
      portalConfig.primaryCtaUrl || ''
    );
    zip.file('sitemap.xml', sitemapXml);
  }

  // 6. Cloudflare Pages configs
  if (options.includeCloudflareConfig) {
    zip.file('_redirects', generateCloudflareRedirects());
    zip.file('_headers', generateCloudflareHeaders());
  }

  // 7. Apache / cPanel .htaccess
  if (options.includeHtaccess) {
    zip.file('.htaccess', generateHtaccess(brand));
  }

  // 8. GitHub Pages
  if (options.includeGithubPagesConfig) {
    zip.file('.nojekyll', '');
  }

  // 9. Documentation
  zip.file('README.md', generateReadmeDeployment(brand));

  return await zip.generateAsync({ type: 'blob' });
}
