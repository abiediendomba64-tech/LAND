import JSZip from 'jszip';
import type {
  AmpConfig,
  PortalConfig,
  RegisterConfig,
  SafeLinkConfig,
  CyberShieldConfig,
  CdnScriptConfig,
} from '../types';
import {
  generateAmpHtml,
  generatePortalHtml,
  generateVipRegisterHtml,
  generateSafeLinkHtml,
} from './generator';
import { generateCyberShieldScript } from '../utils/cyberShield';

export interface DeployPackageOptions {
  primaryLanding: 'amp' | 'portal';
  includeHtaccess: boolean;
  includeCloudflareConfig: boolean;
  includeGithubPagesConfig: boolean;
  includeSitemap: boolean;
  includeCyberShield: boolean;
}

export function generateRobotsTxt(ampCanonical: string, isTransitBlocked: boolean = true): string {
  return `# Robots.txt Generated by Suite Landing Page & Portal
User-agent: *
Allow: /
Allow: /amp.html
Allow: /portal.html
${isTransitBlocked ? `Disallow: /safelink.html\nDisallow: /register.html\nDisallow: /api/\nDisallow: /*?token=\nDisallow: /*?ref=` : ''}

# Disallow aggressive security scanners and scraper crawlers
User-agent: Shodan
Disallow: /

User-agent: CensysInspect
Disallow: /

User-agent: SemrushBot
Disallow: /

User-agent: AhrefsBot
Disallow: /

User-agent: MJ12bot
Disallow: /

Sitemap: ${ampCanonical ? ampCanonical.replace(/\/$/, '') : 'https://vip-official.pages.dev'}/sitemap.xml
`;
}

export function generateSitemapXml(ampUrl: string, portalUrl: string): string {
  const dateStr = new Date().toISOString().split('T')[0];
  const domain = ampUrl ? ampUrl.replace(/\/$/, '') : 'https://vip-official.pages.dev';

  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
  <url>
    <loc>${domain}/</loc>
    <lastmod>${dateStr}</lastmod>
    <changefreq>daily</changefreq>
    <priority>1.0</priority>
  </url>
  <url>
    <loc>${domain}/amp.html</loc>
    <lastmod>${dateStr}</lastmod>
    <changefreq>daily</changefreq>
    <priority>0.9</priority>
  </url>
  <url>
    <loc>${portalUrl || `${domain}/portal.html`}</loc>
    <lastmod>${dateStr}</lastmod>
    <changefreq>daily</changefreq>
    <priority>0.8</priority>
  </url>
</urlset>`;
}

export function generateHtaccess(brandName: string): string {
  return `# ========================================================
# .htaccess for Apache / LiteSpeed / cPanel (public_html/httpdocs)
# Brand: ${brandName}
# ========================================================

RewriteEngine On

# 1. Force HTTPS
RewriteCond %{HTTPS} off
RewriteRule ^(.*)$ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]

# 2. Security Headers
<IfModule mod_headers.c>
  Header set X-Content-Type-Options "nosniff"
  Header set X-XSS-Protection "1; mode=block"
  Header set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set Permissions-Policy "geolocation=(), microphone=(), camera=()"
</IfModule>

# 3. GZIP / Brotli Compression
<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/plain text/xml text/css application/javascript application/json
</IfModule>

# 4. Browser Cache for Static Assets
<IfModule mod_expires.c>
  ExpiresActive On
  ExpiresByType image/jpg "access plus 1 year"
  ExpiresByType image/jpeg "access plus 1 year"
  ExpiresByType image/gif "access plus 1 year"
  ExpiresByType image/png "access plus 1 year"
  ExpiresByType image/webp "access plus 1 year"
  ExpiresByType text/css "access plus 1 month"
  ExpiresByType application/javascript "access plus 1 month"
</IfModule>

# 5. Disable Directory Browsing
Options -Indexes
`;
}

